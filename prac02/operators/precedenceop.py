print((8 + 5) - (8 + 5))
print(100 + 5 * 5)

# Parentheses
print( (2 + 3) * 4)  # Parentheses have the highest precedence

## Exponentiation
print( 2 ** 3)  # 2^3 = 8

## Unary plus, unary minus, and bitwise NOT
x = 5
print(+x)           # +5
print(-x)           # -5
print(~x)           # bitwise NOT (inversion)

## Multiplication, division, floor division, and modulus
print(10 * 3)   # 30
print(10 / 3)   # 3.333...
print(10 // 3) # 3
print(10 % 3)   # 1

## Addition and subtraction
print(10 + 5)   # 15
print(10 - 5)   # 5

## Bitwise left and right shifts
print( 5 << 1)   # 101 -> 1010 (10)
print( 5 >> 1)   # 101 -> 10 (2)

## Bitwise AND
print( 5 & 3)     # 101 & 011 = 001 (1)

## Bitwise XOR
print(5 ^ 3)     # 101 ^ 011 = 110 (6)

## Bitwise OR
print(5 | 3)     # 101 | 011 = 111 (7)

## Comparisons, identity, and membership operators
print(5 > 3)               # True
print(x is None)       # False
print(2 in [1, 2, 3])  # True

## Logical NOT
print(not True)         # False

## AND
print((5 > 3) and (2 < 4))  # True

## OR
print((5 < 3) or (2 < 4))    # True


